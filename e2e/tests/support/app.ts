// Ported for the Android app: one install per device, and the locators the
// app's own widgets expose (Flutter Semantics labels, hintText placeholders,
// localized strings from lib/l10n/app_en.arb).
import { test as base } from '@e2e-dev/mobile';
import type { InstallAppOptions, InstalledApp } from '@e2e-dev/mobile';

/** Installs the target's build without wiping its data; every test takes it. */
export const test = base.extend<{ installed: InstalledApp }>({
  installed: async ({ device }, use) => {
    await use(await device.installApp(undefined, { reinstall: false } satisfies InstallAppOptions));
  },
});

/** Every test on this `test` starts from a cleared app, so onboarding runs fresh. */
export const firstRunTest = test.extend({});
firstRunTest.beforeEach(async ({ app }) => {
  await app.clearState();
  await app.open();
});

